function TabIcon({ name, color, size }: { name: IconName; color: string; size: number }) {
  const icon = ICONS[name];
  return (
    <Svg fill="none" height={size} viewBox={icon.viewBox} width={size}>
      <Path clipRule="evenodd" d={icon.path} fill={color} fillRule="evenodd" />
    </Svg>
  );
}

export function BottomTabBar({ activeTab }: { activeTab: TabName }) {
  const router = useRouter();
  const insets = useSafeAreaInsets();

  return (
    <View style={[styles.tabBar, { paddingBottom: insets.bottom + 4 }]}>
      {TAB_DEFS.map((tab) => {
        const isActive = tab.label === activeTab;
        const color = isActive ? figmaColors.blue["500"] : figmaColors.grayNeutral["400"];
        const iconName = isActive ? tab.iconActive : tab.iconInactive;
        return (
          <Pressable
            key={tab.label}
            accessibilityLabel={tab.label}
            accessibilityRole="tab"
            accessibilityState={{ selected: isActive }}
            onPress={() => {
              if (!isActive && tab.route) router.replace(tab.route as never);
            }}
            style={styles.tabBarItem}
          >
            <TabIcon color={color} name={iconName} size={26} />
            <Text style={[styles.tabLabel, isActive && styles.tabLabelActive]}>
              {tab.label}
            </Text>
          </Pressable>
        );
      })}
    </View>
  );
}

